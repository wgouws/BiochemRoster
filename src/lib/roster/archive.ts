import { days } from "./parse";
import { emptyCells } from "./stations";
import type { Assignment, WeekRoster } from "./types";
import { weekTitle } from "./dates";

type RawCells = Record<string, [string, string, string, string, string]>;
type RawLeave = Record<string, [string, string, string, string, string]>;

function hydrate(
  monday: string,
  notes: string,
  holidays: number[],
  raw: RawCells,
  leave: RawLeave = {},
  title?: string,
): WeekRoster {
  const cells = emptyCells();
  for (const [id, tuple] of Object.entries(raw)) {
    cells[id] = days(tuple[0], tuple[1], tuple[2], tuple[3], tuple[4]);
  }
  const leaveMap: Record<string, string[]> = {};
  for (const [id, tuple] of Object.entries(leave)) {
    leaveMap[id] = [...tuple];
  }
  return {
    monday,
    title: title ?? weekTitle(monday),
    notes,
    cells,
    leave: leaveMap,
    holidays,
  };
}

