export function cloneWeek(w: WeekRoster, monday: string, title: string): WeekRoster {
  const cells: Record<string, Assignment[][]> = {};
  for (const [id, row] of Object.entries(w.cells)) {
    cells[id] = row.map((c) => c.map((a) => ({ ...a })));
  }
  const leave: Record<string, string[]> = {};
  for (const [id, row] of Object.entries(w.leave)) leave[id] = [...row];
  return { monday, title, notes: "", cells, leave, holidays: [] };
}
